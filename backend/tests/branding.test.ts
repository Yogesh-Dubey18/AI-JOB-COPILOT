import request from "supertest";
import { beforeEach, describe, expect, it } from "vitest";
import { app } from "../src/app.js";
import { resetMemoryStore } from "../src/utils/memoryStore.js";
import { updateRecord } from "../src/utils/repository.js";
import { BRANDING_RULE, scrubProviderAttribution } from "../src/agents/branding.js";
import { recordUsageEvent } from "../src/services/usage.service.js";
import { buildGenericPdfBuffer } from "../src/services/pdf-export.service.js";

const PROVIDER_NAMES = /openai|gemini|gpt-|groq|llama|claude|anthropic/i;

async function userAgent(email = "brand-user@example.com") {
  const agent = request.agent(app);
  const register = await agent.post("/api/auth/register").send({ fullName: "Brand User", email, password: "Password123!" }).expect(201);
  return { agent, userId: register.body.data.user.id as string };
}

describe("Provider attribution scrubbing", () => {
  it("removes model self-attribution that is not in the user's data", () => {
    const output = {
      coverLetter: "Dear Hiring Manager, I am excited to apply. (Generated by ChatGPT)",
      answer: "As an AI language model, I suggest tailoring your summary.",
      nested: [{ note: "Written with OpenAI GPT-4o." }],
      score: 72
    };
    const cleaned = scrubProviderAttribution(output, "resume: data analyst, Excel, SQL");
    expect(cleaned.coverLetter).toBe("Dear Hiring Manager, I am excited to apply.");
    expect(cleaned.answer).toBe("I suggest tailoring your summary.");
    expect(cleaned.nested[0].note).toBe("");
    expect(cleaned.score).toBe(72);
  });

  it("removes 'I am <model>' self-identification sentences", () => {
    expect(scrubProviderAttribution("I'm ChatGPT, a model by OpenAI. Here is your plan.", "")).toBe("Here is your plan.");
  });

  it("never alters legitimate content that appears in the user's own data", () => {
    const source = "Projects: Support bot generated with OpenAI. Skills: Gemini API, LangChain. Employer: Anthropic";
    const output = {
      bullet: "Built a support bot generated with OpenAI that cut response time by 30%.",
      skills: ["Gemini API", "LangChain"],
      employer: "Anthropic"
    };
    expect(scrubProviderAttribution(output, source)).toEqual(output);
  });

  it("leaves ordinary text and lowercase starts untouched", () => {
    expect(scrubProviderAttribution("iOS developer with Swift experience", "")).toBe("iOS developer with Swift experience");
  });

  it("keeps the branding rule itself provider-neutral", () => {
    expect(BRANDING_RULE).toMatch(/AI Job Copilot/);
    expect(BRANDING_RULE).not.toMatch(PROVIDER_NAMES);
  });
});

describe("Brand-neutral AI status in public and user-facing responses", () => {
  beforeEach(() => resetMemoryStore());

  it("does not expose the AI provider or model on public status endpoints", async () => {
    for (const path of ["/ready", "/status"]) {
      const res = await request(app).get(path).expect(200);
      const ai = res.body.data.providers.ai;
      expect(ai).toMatchObject({ engine: "AI Job Copilot", mode: "fallback", configured: false, fallbackEnabled: true });
      expect(ai.provider).toBeUndefined();
      expect(ai.model).toBeUndefined();
    }
  });

  it("returns neutral AI status to signed-in users, keeping fallback transparency", async () => {
    const { agent } = await userAgent();
    const status = await agent.get("/api/ai/status").expect(200);
    expect(status.body.data).toMatchObject({ engine: "AI Job Copilot", mode: "fallback", providerConfigured: false, fallbackEnabled: true });
    expect(status.body.data.provider).toBeUndefined();
    expect(status.body.data.model).toBeUndefined();
  });

  it("strips provider and model from user usage data without changing credit totals", async () => {
    const { agent, userId } = await userAgent();
    await agent.post("/api/ai/chat").send({ message: "Plan my week" }).expect(200);
    await recordUsageEvent(userId, "career-chat", 2, "ai", { provider: "openai", model: "gpt-4o-mini", status: "success" });
    const usage = await agent.get("/api/ai/usage").expect(200);
    const events = usage.body.data.events;
    expect(events.length).toBeGreaterThan(0);
    for (const event of events) {
      expect(event.provider).toBeUndefined();
      expect(event.model).toBeUndefined();
      expect(event.engine).toBe("AI Job Copilot");
      expect(["ai", "fallback"]).toContain(event.mode);
    }
    for (const event of usage.body.data.usageEvents) {
      expect(event.metadata?.provider).toBeUndefined();
      expect(event.metadata?.model).toBeUndefined();
    }
    expect(usage.body.data.usedCredits).toBeGreaterThan(0);
  });

  it("lists the AI engine without third-party AI names in job source status", async () => {
    const res = await request(app).get("/api/jobs/sources").expect(200);
    const engine = res.body.data.externalProviders.find((provider: any) => provider.id === "ai-engine");
    expect(engine).toMatchObject({ name: "AI engine", isLive: false });
    expect(JSON.stringify(engine)).not.toMatch(PROVIDER_NAMES);
  });

  it("keeps provider and model details for admin monitoring", async () => {
    const admin = request.agent(app);
    const register = await admin.post("/api/auth/register").send({ fullName: "Admin", email: "brand-admin@example.com", password: "Password123!" }).expect(201);
    await updateRecord("users", register.body.data.user.id, { role: "admin" });
    const health = await admin.get("/api/admin/system-health").expect(200);
    expect(health.body.data.ai.provider).toBeTruthy();
    expect(health.body.data.ai.model).toBeDefined();
    expect(health.body.data.providers.ai.provider).toBeTruthy();
  });
});

describe("PDF branding", () => {
  it("sets AI Job Copilot as the document creator without adding visible text", async () => {
    const pdf = await buildGenericPdfBuffer("Interview prep", [{ heading: "Topics", lines: ["SQL joins"] }]);
    const raw = pdf.toString("latin1");
    const infoValue = (key: string) => {
      const ref = raw.match(new RegExp(`/${key} (\\d+) 0 R`))?.[1];
      return ref ? raw.match(new RegExp(`\\n${ref} 0 obj\\n\\((.*?)\\)\\nendobj`))?.[1] : undefined;
    };
    expect(infoValue("Creator")).toBe("AI Job Copilot");
    expect(infoValue("Title")).toBe("Interview prep");
    expect(raw).not.toMatch(PROVIDER_NAMES);
  });
});
